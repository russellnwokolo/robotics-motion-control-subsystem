/* USER CODE BEGIN 4 */
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART2)
    {
        // STATE 1: We were hunting for the 1-byte header
        if (huart->RxXferSize == 1)
        {
            if (rx_buffer[0] == 0xAA)
            {
                // Header found! Tell DMA to read the remaining 10 bytes of this packet
                // Notice we offset the array pointer by 1 (&rx_buffer[1])
                // so we don't overwrite the header!
                HAL_UART_Receive_DMA(&huart2, &rx_buffer[1], 10);
            }
            else
            {
                // Garbage/misaligned byte. Keep listening 1 byte at a time until we see 0xAA
                HAL_UART_Receive_DMA(&huart2, rx_buffer, 1);
            }
        }

        // STATE 2: We just finished reading the 10-byte payload
        else if (huart->RxXferSize == 10)
        {
            // Calculate checksum on the 9 data bytes (Indices 1 through 9)
            uint16_t sum = 0;
            for (int i = 1; i <= 9; i++) {
                sum += rx_buffer[i];
            }

            // Compare our calculated sum to the received checksum (Index 10)
            if ((sum % 256) == rx_buffer[10])
            {
                // Packet is perfectly valid! Safely copy memory to floats
                memcpy((void*)&target_yaw, &rx_buffer[1], 4);
                memcpy((void*)&target_pitch, &rx_buffer[5], 4);
                fire_command = rx_buffer[9];
            }

            // Packet processed (or discarded because checksum failed).
            // Go back to searching for the next header!
            HAL_UART_Receive_DMA(&huart2, rx_buffer, 1);
        }
    }
}

void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
    if (htim->Instance == TIM2)
    {
        // 1. Run PID for Yaw (using target_yaw received from UART)
        // Note: Replace `current_yaw` with your actual encoder/position variable when ready
        float pid_output = calculate_PID(&yaw_pid, target_yaw, current_yaw);

        // 2. Handle Direction Pin (D6_DIR_Pin)
        if (pid_output >= 0)
        {
            HAL_GPIO_WritePin(D6_DIR_GPIO_Port, D6_DIR_Pin, GPIO_PIN_SET);
        }
        else
        {
            HAL_GPIO_WritePin(D6_DIR_GPIO_Port, D6_DIR_Pin, GPIO_PIN_RESET);
            pid_output = -pid_output; // Make magnitude positive for frequency conversion
        }

        if (pid_output > 4000.0f) pid_output = 4000.0f;

        // 3. Map PID output to Step Frequency (Hz)
        uint32_t target_frequency = (uint32_t)pid_output;

        // If error is tiny, slow/stop the step generation
        if (target_frequency < 5)
        {
            __HAL_TIM_SET_AUTORELOAD(&htim3, 65535); // Very slow tick rate
            __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1, 32767);
        }
        else
        {
            // Since TIM3 is clocked at 1 MHz (72 MHz / 71+1),
            // Period Ticks = 1,000,000 / Frequency
            uint32_t period_ticks = 1000000 / target_frequency;

            // Constrain limits to prevent overflow or out-of-bounds math
            if (period_ticks < 2) period_ticks = 2;       // Max speed cap
            if (period_ticks > 65535) period_ticks = 65535; // Min speed cap (16-bit timer limit)

            __HAL_TIM_SET_AUTORELOAD(&htim3, period_ticks - 1);
            __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1, period_ticks / 2); // 50% duty cycle
        }
    }
}
