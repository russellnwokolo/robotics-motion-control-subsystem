/* USER CODE BEGIN 0 */
float calculate_PID(PID_Controller *pid, float setpoint, float current_position) {
    // 1. Calculate current error
    float error = setpoint - current_position;

    // 2. Calculate Integral (accumulated past error)
    pid->integral += error;

    // Optional but highly recommended: Integral Anti-Windup
    // Prevents the integral from growing infinitely if the turret gets physically stuck
    if (pid->integral > 1000.0f) pid->integral = 1000.0f;
    if (pid->integral < -1000.0f) pid->integral = -1000.0f;

    // 3. Calculate Derivative (rate of change)
    float derivative = error - pid->previous_error;

    // 4. Save current error for the next loop
    pid->previous_error = error;

    // 5. Calculate the final output to send to the motor
    return (pid->Kp * error) + (pid->Ki * pid->integral) + (pid->Kd * derivative);
}

